-- Migration 000005: Realtime tickets and notifications

CREATE TABLE IF NOT EXISTS realtime_tickets (
    token_hash TEXT PRIMARY KEY,
    user_id TEXT NOT NULL,
    role TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_realtime_tickets_expires_at ON realtime_tickets(expires_at);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    role_target TEXT NOT NULL,
    type TEXT NOT NULL,
    dedupe_key TEXT NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ,
    CONSTRAINT uq_notifications_type_dedupe UNIQUE (type, dedupe_key)
);
CREATE INDEX IF NOT EXISTS idx_notifications_role_read ON notifications(role_target, read_at, created_at DESC);
